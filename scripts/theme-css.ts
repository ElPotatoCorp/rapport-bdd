import postcss, {
  type AtRule,
  type ChildNode,
  type Root,
  type Rule,
} from "postcss";

export type ThemeVars = Record<string, string>;

export interface ParsedTheme {
  /** Variables declared in `@theme` (not `@theme inline`) and in `:root` */
  light: ThemeVars;
  /** Variables declared in `.dark` (overrides only) */
  dark: ThemeVars;
}

export type ThemeInput = ParsedTheme;

const DARK_SELECTOR = ".dark";
const LIGHT_SELECTORS: ReadonlySet<string> = new Set([":root"]);
const DARK_SELECTORS: ReadonlySet<string> = new Set([
  DARK_SELECTOR,
  `:root${DARK_SELECTOR}`,
  `html${DARK_SELECTOR}`,
]);

const OVERRIDES_HEADER =
  "/* Generated by the theme panel: overrides style.css. Empty this file to revert. */\n";

type Block = AtRule | Rule;

const isThemeAtRule = (n: ChildNode): n is AtRule =>
  n.type === "atrule" && n.name === "theme";

/** `@theme inline` only holds `var(--c-*)` bridges to the raw variables: not editable values. */
const isInline = (rule: AtRule) => rule.params.split(/\s+/).includes("inline");

const isLightBlock = (n: ChildNode): n is Block =>
  (isThemeAtRule(n) && !isInline(n)) ||
  (n.type === "rule" && LIGHT_SELECTORS.has(n.selector.trim()));

const isDarkBlock = (n: ChildNode): n is Rule =>
  n.type === "rule" && DARK_SELECTORS.has(n.selector.trim());

/**
 * Top-level blocks, plus the direct children of top-level `@layer` blocks
 * (that is where `:root` and `.dark` live). Never deeper, so variables nested
 * in `@media`, `@supports`, etc. are left alone.
 */
function findBlocks<T extends Block>(
  root: Root,
  match: (node: ChildNode) => node is T,
): T[] {
  const found: T[] = [];
  const visit = (nodes: ChildNode[]) => {
    for (const node of nodes) {
      if (match(node)) found.push(node);
      else if (node.type === "atrule" && node.name === "layer" && node.nodes) {
        visit(node.nodes);
      }
    }
  };
  visit(root.nodes);
  return found;
}

function collect(blocks: Block[]): ThemeVars {
  const vars: ThemeVars = {};
  for (const block of blocks) {
    block.each((node) => {
      if (node.type !== "decl" || !node.prop.startsWith("--")) return;
      // Namespace resets such as `--color-*: initial` are not editable values
      if (node.prop.includes("*")) return;
      vars[node.prop] = node.value;
    });
  }
  return vars;
}

/** Works for both style.css (the baseline) and the generated vars.css. */
export function parseTheme(css: string): ParsedTheme {
  const root = postcss.parse(css);
  return {
    light: collect(findBlocks(root, isLightBlock)),
    dark: collect(findBlocks(root, isDarkBlock)),
  };
}

/**
 * What the panel should show: baseline + overrides. A dark value equal to the
 * light one means "same as light", so it is reported as no dark override.
 */
export function mergeTheme(
  base: ParsedTheme,
  overrides: ParsedTheme,
): ParsedTheme {
  const light = { ...base.light, ...overrides.light };

  // An unlayered `:root` override also shadows the layered baseline `.dark`
  // for that variable, unless vars.css sets `.dark` itself.
  const dark: ThemeVars = {};
  for (const [prop, value] of Object.entries(base.dark)) {
    if (!(prop in overrides.light)) dark[prop] = value;
  }
  Object.assign(dark, overrides.dark);
  for (const [prop, value] of Object.entries(dark)) {
    if (value === light[prop]) delete dark[prop];
  }
  return { light, dark };
}

const isSafeProp = (prop: string) => /^--[\w-]+$/.test(prop);
/**
 * A value may not close its declaration or open/close a block. `;` is fine
 * inside parentheses or quotes (`url(data:...;base64,...)`), multi-line
 * values (gradients) are fine too.
 */
function isSafeValue(value: string): boolean {
  let depth = 0;
  let quote: string | null = null;
  for (const ch of value) {
    if (quote) {
      if (ch === quote) quote = null;
    } else if (ch === '"' || ch === "'") {
      quote = ch;
    } else if (ch === "(") {
      depth++;
    } else if (ch === ")") {
      depth--;
    } else if (ch === "{" || ch === "}" || (ch === ";" && depth <= 0)) {
      return false;
    }
  }
  return quote === null && depth === 0;
}

function block(selector: string, decls: [string, string][]): string {
  if (decls.length === 0) return "";
  const body = decls.map(([prop, value]) => `  ${prop}: ${value};`).join("\n");
  return `${selector} {\n${body}\n}\n`;
}

/**
 * Generates the full content of vars.css: only what differs from the baseline.
 * Only variables present in `input.light` are considered.
 *
 * vars.css is unlayered, so it beats the baseline in `@layer base` whatever
 * the order. Consequence: a light override in `:root` also beats the
 * baseline `.dark` for the same variable, so dark mode would silently show
 * the light value. `fallback` models that: `.dark` is only emitted when the
 * wanted dark value is not what the page would show without it.
 * `:root` is emitted before `.dark` on purpose: equal specificity, order wins.
 */
export function buildOverrides(base: ParsedTheme, input: ThemeInput): string {
  const lightDecls: [string, string][] = [];
  const darkDecls: [string, string][] = [];

  for (const [prop, light] of Object.entries(input.light)) {
    const dark = input.dark[prop] ?? light;
    for (const [p, v] of [
      [prop, light],
      [prop, dark],
    ] as const) {
      if (!isSafeProp(p) || !isSafeValue(v)) {
        throw new Error(`Refusing unsafe declaration: ${p}: ${v}`);
      }
    }

    const lightChanged = light !== base.light[prop];
    if (lightChanged) lightDecls.push([prop, light]);

    const fallback = lightChanged
      ? light
      : (base.dark[prop] ?? base.light[prop]);
    if (dark !== fallback) darkDecls.push([prop, dark]);
  }

  return [
    OVERRIDES_HEADER,
    block(":root", lightDecls),
    block(DARK_SELECTOR, darkDecls),
  ]
    .filter(Boolean)
    .join("\n");
}
